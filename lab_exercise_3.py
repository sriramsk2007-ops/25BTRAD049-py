# Program to demonstrate variables, operators, and input/output

# ---- Variables (different data types) ----
name = "Sriram Satvik       "
age = 19
cgpa = 8.75
is_student = True

# ---- Arithmetic Operators ----
num1 = 15
num2 = 4
print("---- Arithmetic Operators ----")
print("Addition:", num1 + num2)
print("Subtraction:", num1 - num2)
print("Multiplication:", num1 * num2)
print("Division:", num1 / num2)
print("Floor Division:", num1 // num2)
print("Modulus:", num1 % num2)
print("Exponent:", num1 ** 2)

# ---- Comparison Operators ----
print("\n---- Comparison Operators ----")
print("num1 == num2:", num1 == num2)
print("num1 != num2:", num1 != num2)
print("num1 > num2:", num1 > num2)

# ---- Logical Operators ----
print("\n---- Logical Operators ----")
print("(num1 > 10) and (num2 < 10):", (num1 > 10) and (num2 < 10))
print("(num1 > 100) or (num2 < 10):", (num1 > 100) or (num2 < 10))
print("not is_student:", not is_student)

# ---- Output of Variables ----
print("\n---- Student Details (Output) ----")
print("Name:", name)
print("Age:", age)
print("CGPA:", cgpa)
print("Is Student:", is_student)
